TEMPLATE = r'''// Vortex support for __NAME__, built on Blobset Tools.
//
// Generated by Blobset Tools (tools/make_vortex_extensions.py) - edit the template there, not this file.
//
// Vortex deploys the mods into <game>\BlobsetToolsMods. The game reads blobsets, not loose files, so after every
// deploy / purge this extension runs Blobset Tools on the command line:
//     Blobset-Tools.exe --game "<game>" --platform pc --game-location "<game folder>" --build
// which puts the files into the game (or, with nothing deployed, restores the original files).
// Blobset Tools' path comes from config.json (written by "Blobset-Tools.exe --install-vortex-extensions").
const path = require('path');
const fs = require('fs');
const { spawn } = require('child_process');
const { util } = require('vortex-api');

const GAME = __GAME__;
const MOD_FOLDER = 'BlobsetToolsMods';
const CONFIG = path.join(__dirname, 'config.json');
const BUILD_DELAY_MS = 1500;   // A purge followed by a deploy builds once.

// Top level folders of the games' file mappings: a mod archive's root is the folder that holds these.
const STOP_PATTERNS = [
  'anim', 'body_shapes', 'characters', 'collision', 'crowd', 'dds_txpk', 'editor', 'fields', 'font', 'fonts',
  'grass', 'heads', 'hj_offsets', 'm3mp', 'material', 'model', 'noesis', 'objects', 'players', 'png', 'props',
  'sound', 'stadiumcreator', 'stadiums', 'text', 'textures', 'txpl', 'ui', 'unknown',
].map(folder => `(^|/)${folder}(/|$)`);

function findGame() {
  if (!GAME.steamAppId) {
    return Promise.reject(new util.NotFound(GAME.name));   // Not on Steam: set the folder by hand in Vortex.
  }
  return util.GameStoreHelper.findByAppId([GAME.steamAppId]).then(game => game.gamePath);
}

// The exe, when it isn't known up front: the biggest one in the game folder (helpers and installers left out).
function executable(discoveredPath) {
  if (GAME.exe) {
    return GAME.exe;
  }
  if (discoveredPath) {
    try {
      const skip = /unins|crash|setup|redist|launcher|vc_?redist|dxsetup|report/i;
      const exes = fs.readdirSync(discoveredPath)
        .filter(file => /\.exe$/i.test(file) && !skip.test(file))
        .map(file => ({ file, size: fs.statSync(path.join(discoveredPath, file)).size }))
        .sort((a, b) => b.size - a.size);
      if (exes.length > 0) {
        return exes[0].file;
      }
    } catch (err) {
      // Fall through.
    }
  }
  return 'game.exe';
}

function prepareForModding(discovery) {
  return new Promise((resolve, reject) => {
    fs.mkdir(path.join(discovery.path, MOD_FOLDER), { recursive: true }, err => (err ? reject(err) : resolve()));
  });
}

// ---------------------------------------------------------------------------------------------------------------
// Blobset Tools
// ---------------------------------------------------------------------------------------------------------------

function readToolPath() {
  try {
    const tool = JSON.parse(fs.readFileSync(CONFIG, 'utf8')).blobsetToolsPath;
    return tool && fs.existsSync(tool) ? tool : undefined;
  } catch (err) {
    return undefined;
  }
}

function askForToolPath(api) {
  return api.selectFile({
    title: 'Where is Blobset-Tools.exe?',
    filters: [{ name: 'Blobset Tools', extensions: ['exe'] }],
  }).then(selected => {
    if (!selected) {
      return undefined;
    }
    fs.writeFileSync(CONFIG, JSON.stringify({ blobsetToolsPath: selected }, null, 2));
    return selected;
  });
}

function runBlobsetTools(tool, args) {
  return new Promise(resolve => {
    let output = '';
    let child;
    try {
      child = spawn(tool, args, { cwd: path.dirname(tool), windowsHide: true });
    } catch (err) {
      resolve({ code: -1, output: err.message });
      return;
    }
    child.stdout.on('data', data => { output += data.toString(); });
    child.stderr.on('data', data => { output += data.toString(); });
    child.on('error', err => resolve({ code: -1, output: output + err.message }));
    child.on('close', code => resolve({ code, output }));
  });
}

function lastLines(text, count) {
  return text.split(/\r?\n/).filter(line => line.trim() !== '').slice(-count).join('\n');
}

let buildTimer;
let buildQueue = Promise.resolve();

function build(api, gamePath) {
  const notificationId = `blobset-tools-build-${GAME.id}`;
  return Promise.resolve(readToolPath() || askForToolPath(api)).then(tool => {
    if (!tool) {
      api.sendNotification({
        type: 'warning',
        message: 'Blobset Tools wasn\'t found, so the mods weren\'t put into the game. '
               + 'Run "Blobset-Tools.exe --install-vortex-extensions" and deploy again.',
      });
      return;
    }
    api.sendNotification({ id: notificationId, type: 'activity', message: `Blobset Tools: building the mods for ${GAME.name}...` });
    const args = ['--game', GAME.blobsetToolsGame, '--platform', 'pc', '--game-location', gamePath, '--build', '--quiet'];
    return runBlobsetTools(tool, args).then(({ code, output }) => {
      api.dismissNotification(notificationId);
      if (code === 0) {
        api.sendNotification({ type: 'success', message: `Blobset Tools: the mods are in ${GAME.name}.`, displayMS: 5000 });
      } else if (code === 3) {
        api.sendNotification({
          type: 'warning',
          message: 'Blobset Tools is open (or still busy). Close it, then deploy again to put the mods into the game.',
        });
      } else {
        api.showErrorNotification('Blobset Tools couldn\'t put the mods into the game',
          `${lastLines(output, 15)}\n\nThe full log is cli.log in Documents\\Blobset Tools.`, { allowReport: false });
      }
    });
  });
}

function scheduleBuild(api, profileId) {
  const state = api.store.getState();
  const profile = state.persistent.profiles[profileId];
  if (profile === undefined || profile.gameId !== GAME.id) {
    return Promise.resolve();
  }
  const discovery = util.getSafe(state, ['settings', 'gameMode', 'discovered', GAME.id], undefined);
  if (discovery === undefined || discovery.path === undefined) {
    return Promise.resolve();
  }
  clearTimeout(buildTimer);
  buildTimer = setTimeout(() => {
    buildQueue = buildQueue.then(() => build(api, discovery.path)).catch(err => api.showErrorNotification('Blobset Tools', err));
  }, BUILD_DELAY_MS);
  return Promise.resolve();
}

// ---------------------------------------------------------------------------------------------------------------

function main(context) {
  context.registerGame({
    id: GAME.id,
    name: GAME.name,
    mergeMods: true,
    queryPath: findGame,
    queryModPath: () => MOD_FOLDER,
    logo: 'gameart.png',
    executable,
    requiredFiles: [GAME.blobset],
    setup: prepareForModding,
    requiresLauncher: GAME.steamAppId ? () => Promise.resolve({ launcher: 'steam', addInfo: GAME.steamAppId }) : undefined,
    environment: GAME.steamAppId ? { SteamAPPId: GAME.steamAppId } : {},
    details: {
      steamAppId: GAME.steamAppId ? parseInt(GAME.steamAppId, 10) : undefined,
      stopPatterns: STOP_PATTERNS,
    },
  });

  context.once(() => {
    context.api.onAsync('did-deploy', profileId => scheduleBuild(context.api, profileId));
    context.api.onAsync('did-purge', profileId => scheduleBuild(context.api, profileId));
  });

  return true;
}

module.exports = { default: main };
'''

def game_id(name):
    return re.sub(r'[^a-z0-9]', '', name.lower())

def main():
    os.makedirs(OUT, exist_ok=True)
    for name, bt_game, steam, blobset, exe, art in GAMES:
        gid = game_id(name)
        folder = os.path.join(OUT, 'game-' + gid)
        os.makedirs(folder, exist_ok=True)
        game = {'id': gid, 'name': name, 'blobsetToolsGame': bt_game, 'steamAppId': steam, 'blobset': blobset, 'exe': exe}
        with open(os.path.join(folder, 'index.js'), 'w', newline='\n') as f:
            f.write(TEMPLATE.replace('__NAME__', name).replace('__GAME__', json.dumps(game, indent=2)))
        with open(os.path.join(folder, 'info.json'), 'w', newline='\n') as f:
            json.dump({'name': f'Game: {name} (Blobset Tools)', 'author': 'Wouldy Mods', 'version': '1.0.0',
                       'description': f'Vortex support for {name}: mods are put into the game by Blobset Tools.'}, f, indent=2)
        # Which Blobset Tools game this is: --install-vortex-extensions only installs the games picked in setup.
        with open(os.path.join(folder, 'blobset_game.json'), 'w', newline='\n') as f:
            json.dump({'game': bt_game}, f)
        src = os.path.join(ROOT, 'assets', 'games', art)
        if os.path.exists(src):
            shutil.copyfile(src, os.path.join(folder, 'gameart.png'))
        else:
            print('note: no art for', name, '(' + src + ')', file=sys.stderr)
    print(f'{len(GAMES)} extension(s) written to {OUT}')

if __name__ == '__main__':
    main()
