QStringList strings(const char* const* a, size_t n) {
    QStringList out;
    out.reserve(qsizetype(n));
    for (size_t i = 0; i < n; ++i)
        out << QString::fromUtf8(a[i]);
    return out;
}
template <typename T, size_t N>
QList<T> toList(const T (&a)[N]) { return QList<T>(a, a + N); }
